def _build():
    roles = {}
    for role, skus in _SKU_ROLES.items():
        for sku in skus:
            if sku in roles:
                raise ValueError("Duplicate buyer-guidance role for " + sku)
            roles[sku] = role
    result = {}
    for sku, role in roles.items():
        lead, checklist = _COPY[role]
        hint = _HINTS[_HINT_ROLE[role]].format(sku=sku)
        if sku == "7206-0435":
            hint = "Актуатор 7206-0435; номер насос-форсунки; модель двигателя; количество"
        result[sku] = {
            "lead": _LEAD_OVERRIDES.get(sku, lead),
            "checklist": list(checklist),
            "request_hint": hint,
            "role": _TYPE_ROLES[role],
        }
    return result


